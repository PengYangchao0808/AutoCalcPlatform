def _load_json(path: Path) -> dict[str, object]:
    return json.loads(path.read_text(encoding="utf-8"))


def _layer_tol(layer: str) -> dict[str, float]:
    tolerances = _load_json(TOLERANCES_PATH)
    entry = tolerances["layers"][layer]  # type: ignore[index]
    return {"rtol": float(entry["rtol"]), "atol": float(entry["atol"])}


def _assert_layer_close(
    layer: str, actual: object, expected: object, tol: dict[str, float]
) -> None:
    """Assert one layer against the frozen golden with its frozen tolerance.

    The failure message names the layer and the max observed deviation so a
    breach in a lower layer cannot hide behind a passing final probability.
    """
    a = np.asarray(actual, dtype=float)
    g = np.asarray(expected, dtype=float)
    assert a.shape == g.shape, f"layer={layer}: shape {a.shape} != golden shape {g.shape}"
    dev = np.abs(a - g)
    allowed = float(tol["atol"]) + float(tol["rtol"]) * np.abs(g)
    over = dev > allowed
    if np.any(over):
        worst_flat = int(np.argmax(np.where(over, dev - allowed, -np.inf)))
        worst = np.unravel_index(worst_flat, dev.shape)
        raise AssertionError(
            f"layer={layer} FAILED vs frozen golden: max_abs_dev={float(np.max(dev)):.6e} "
            f"(frozen rtol={tol['rtol']:.1e}, atol={tol['atol']:.1e}); "
            f"{int(np.count_nonzero(over))}/{dev.size} entries exceed; "
            f"worst at {worst}: actual={a[worst]!r} golden={g[worst]!r}"
        )


