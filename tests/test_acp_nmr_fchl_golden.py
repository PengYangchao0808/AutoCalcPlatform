def test_layer2_kernel_backend_three_states(monkeypatch: pytest.MonkeyPatch) -> None:
    """numpy / qml / unavailable are three explicit states — never a stub.

    With no compiled ``qml`` and no opt-in, FCHL is inactive (``""``); the
    numpy opt-in activates the pure-numpy port; a genuinely importable ``qml``
    takes precedence.  The expected branch is derived from the real
    :func:`qml_kernel_available` probe, not hardcoded, so this test records the
    environment honestly on every host.
    """
    assert "qml.fchl" not in sys.modules  # autouse isolation: no stub present
    monkeypatch.delenv("ACP_FCHL_NUMPY", raising=False)
    qml_available = qml_kernel_available()
    expected_default = "qml" if qml_available else ""
    assert kernel_backend() == expected_default
    monkeypatch.setenv("ACP_FCHL_NUMPY", "1")
    assert kernel_backend() == ("qml" if qml_available else "numpy")


