"""Layered FCHL golden parity tests (plan todo 36; gap investigation §10.2/§10.3 trial A).

Layer-by-layer comparison against a frozen golden produced from the
``dp5@b6cf559007a5d13fe79654f37daf945ee1661a23`` assets checked into
``src/acp/nmr/models/`` so a failure in one layer cannot be masked by a
"close enough" final probability (gap §10.2: 不能为了让最终概率相近而掩盖
descriptor/kernel 层的系统差异):

1. **descriptor** — :func:`acp.nmr.fchl.build_atom_representations` for a fixed
   ethanol geometry (two carbon atoms) vs frozen ``(5, 86)`` arrays.
2. **kernel** — :func:`acp.nmr.fchl.get_atomic_kernels_numpy` (pure-numpy port
   of the compiled Fortran reference) vs frozen kernels; when ``qml`` is
   importable the compiled-kernel parity layer also runs against the same
   frozen numpy golden (skipped with an explicit ``NOT_VERIFIED`` reason when
   absent — no stub ever stands in for the compiled kernel).
3. **weighted KDE** — :func:`acp.nmr.fchl.atom_probability_fchl` on the full
   checked-in ``folded_scaled_errors.p`` residual set with *fixed* weights
   (the kernel seam is pinned, so this layer is independent of kernel-layer
   correctness), plus the ``sum(K_sim) == 0`` unweighted fallback.
4. **candidate probability** — the public ``GoodmanDP5Model`` seams
   ``probability_per_conformer`` / ``probability`` on the full checked-in
   assets, and ``probability_per_conformer_fchl`` on a pinned slice of the
   training set (runtime note below).

Runtime note (why layer 4's FCHL path slices the training set): the pure-numpy
kernel costs ~28 ms per training atom, i.e. ~25 min per query atom against the
full 53 208-atom ``atomic_reps.gz``.  The FCHL candidate layer therefore runs
on the first ``FCHL_REDUCED_TRAIN_SLICE`` training atoms and the first
``2 * FCHL_REDUCED_TRAIN_SLICE`` folded residuals (the 2x fold pairing is
preserved exactly; the KDE-rescale assets are reused verbatim).  The slicing is
deterministic and derived from the NOTICE-pinned assets; layer 2 anchors the
real kernel and layer 3 anchors the real KDE on the full residual set, so no
scientific information is silently dropped — the full-fat FCHL call is
recorded as out of unit-test budget, not as verified.

Tolerances are frozen in ``tests/baseline/nmr/fchl_golden_tolerances.json``
after measuring real repeatability (in-process repeats and fresh-process
regeneration were bit-identical; see the ``measurement`` block in that file).
The golden itself is generated by
``tests/baseline/nmr/generate_fchl_goldens.py``, which imports
:func:`compute_layer_values` from this module so the committed golden and the
assertions can never drift into two implementations.  Regenerate with:

    PYTHONPATH=src python3.11 tests/baseline/nmr/generate_fchl_goldens.py

Do not relax a layer tolerance to make a failing layer pass — re-measure and
re-freeze deliberately (and update the evidence/measurement block).
"""

