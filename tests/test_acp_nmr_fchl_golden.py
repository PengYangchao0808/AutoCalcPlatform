def _build_reduced_models_dir(
    workdir: Path, atomic_reps: np.ndarray, folded_errors: np.ndarray
) -> Path:
    """Create a reduced DP5 model dir from a pinned slice of the real assets.

    The KDE-rescale assets (``c_w_kde_mean_s_0.025.p`` /
    ``i_w_kde_mean_s_0.025.p``) and ``frag_reps.gz`` are linked verbatim; only
    the per-atom training side is sliced (see the module docstring runtime
    note).  The folded residuals are sliced to ``2 * n_atoms`` to preserve the
    doubled kernel/residual pairing.
    """
    reduced = workdir / "reduced_models"
    if reduced.exists():
        shutil.rmtree(reduced)
    reduced.mkdir(parents=True)
    for name in ("c_w_kde_mean_s_0.025.p", "i_w_kde_mean_s_0.025.p", "frag_reps.gz"):
        (reduced / name).symlink_to(MODELS_DIR / name)
    n_atoms = FCHL_REDUCED_TRAIN_SLICE
    with (reduced / "folded_scaled_errors.p").open("wb") as fh:
        pickle.dump(folded_errors[: 2 * n_atoms], fh)
    with gzip.open(reduced / "atomic_reps.gz", "wb") as fh:
        pickle.dump(atomic_reps[:n_atoms], fh)
    return reduced


def compute_layer_values(workdir: Path) -> dict[str, object]:
    """Compute every golden layer value from the frozen inputs.

    Both the tests (via the module-scoped ``layer_values`` fixture) and
    ``tests/baseline/nmr/generate_fchl_goldens.py`` call this function, so the
    committed golden and the assertions share one computation path.
    """
    atomic_reps = load_atomic_reps()
    conf1 = np.asarray(ETHANOL_CONFORMER_1, dtype=float)
    conf2 = np.asarray(ETHANOL_CONFORMER_2, dtype=float)
    conf3 = np.asarray(ETHANOL_CONFORMER_3, dtype=float)
    reps1 = build_atom_representations(conf1, ETHANOL_SYMBOLS, CARBON_ATOM_INDICES)
    reps2 = build_atom_representations(conf2, ETHANOL_SYMBOLS, CARBON_ATOM_INDICES)
    reps3 = build_atom_representations(conf3, ETHANOL_SYMBOLS, CARBON_ATOM_INDICES)

    kernel_query = get_atomic_kernels_numpy(
        np.array([reps1[0], reps1[1]]), atomic_reps[:KERNEL_TRAIN_SLICE], [KERNEL_SIGMA]
    )
    kernel_self = get_atomic_kernels_numpy(
        atomic_reps[:KERNEL_SELF_SLICE], atomic_reps[:KERNEL_SELF_SLICE], [KERNEL_SIGMA]
    )

    model = GoodmanDP5Model()
    folded = model.folded_errors
    weights = np.linspace(0.001, 1.0, folded.size)
    dummy_reps = np.zeros((1, 5, 86))
    query_rep = reps1[0]
    with patch("acp.nmr.fchl.atom_kernel_similarities", return_value=weights):
        kde_weighted = [
            atom_probability_fchl(query_rep, se, folded, model.mean_abs_error, dummy_reps)
            for se in KDE_SCALED_ERRORS
        ]
    with patch("acp.nmr.fchl.atom_kernel_similarities", return_value=np.zeros_like(weights)):
        kde_zero_weight = [
            atom_probability_fchl(query_rep, se, folded, model.mean_abs_error, dummy_reps)
            for se in KDE_SCALED_ERRORS
        ]

    probability_per_conformer = model.probability_per_conformer(
        CANDIDATE_CONFORMER_CALC_SHIFTS, CANDIDATE_EXP_SHIFTS, CANDIDATE_BOLTZMANN_WEIGHTS
    )
    probability_single = model.probability(CANDIDATE_SINGLE_SCALED_ERRORS)

    reduced_dir = _build_reduced_models_dir(workdir, atomic_reps, folded)
    reduced_model = GoodmanDP5Model(models_dir=reduced_dir)
    conformer_reps = [[rep for rep in reps1], [rep for rep in reps2], [rep for rep in reps3]]
    # Pin the backend to numpy so the frozen golden is deterministic even on a
    # host where the compiled qml kernel is importable (qml parity is layer 2).
    with patch("acp.nmr.fchl.kernel_backend", return_value="numpy"):
        probability_fchl = reduced_model.probability_per_conformer_fchl(
            CANDIDATE_CONFORMER_CALC_SHIFTS,
            CANDIDATE_EXP_SHIFTS,
            CANDIDATE_BOLTZMANN_WEIGHTS,
            conformer_reps,
        )

    return {
        "descriptor_c0": reps1[0].tolist(),
        "descriptor_c1": reps1[1].tolist(),
        "kernel_numpy_query_train32": kernel_query.tolist(),
        "kernel_numpy_self4": kernel_self.tolist(),
        "kde_weighted_fixed": kde_weighted,
        "kde_zero_weight_fallback": kde_zero_weight,
        "probability_per_conformer": probability_per_conformer,
        "probability_single": probability_single,
        "probability_per_conformer_fchl_reduced32": probability_fchl,
    }


