def test_golden_provenance_and_tolerance_coverage() -> None:
    golden = _load_json(GOLDEN_PATH)
    tolerances = _load_json(TOLERANCES_PATH)

    assert golden["schema"] == "acp_nmr_fchl_layers_golden_v1"
    assert golden["dp5_revision"] == DP5_REVISION
    assert tolerances["dp5_revision"] == DP5_REVISION
    actual_golden_sha = hashlib.sha256(GOLDEN_PATH.read_bytes()).hexdigest()
    assert tolerances["golden_sha256"] == actual_golden_sha, (
        "fchl_golden.json bytes differ from the sha256 frozen in "
        "fchl_golden_tolerances.json — re-measure and re-freeze deliberately "
        "(do not edit either file to silence a layer failure)"
    )

    for name, expected in ASSET_SHA256.items():
        actual = hashlib.sha256((MODELS_DIR / name).read_bytes()).hexdigest()
        assert actual == expected, (
            f"asset {name} drifted from dp5@{DP5_REVISION}: "
            f"expected sha256 {expected}, got {actual}; re-freeze the golden "
            "deliberately (and update NOTICE.md) instead of relaxing tolerances"
        )
    assert golden["asset_sha256"] == ASSET_SHA256

    # Golden inputs must mirror the in-test frozen inputs (drift guard).
    assert golden["inputs"] == golden_inputs_metadata()

