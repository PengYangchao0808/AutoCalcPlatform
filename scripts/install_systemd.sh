#!/usr/bin/env bash
# Install / refresh the systemd unit for the ACP web service.
#
# Resolves the current project location from this script's path and writes
# /etc/systemd/system/acp.service with the correct absolute paths, so the
# project can be relocated freely — just move the directory and re-run this
# script.
#
# Usage: scripts/install_systemd.sh [--user <user>] [--enable]
#        [--public-origin https://acp.example] [--origin-only]
# --origin-only configures an existing service without replacing its unit.
# Use --run-root /absolute/path --run-root-only to relocate an existing service.
# Use --run-root '' --run-root-only to read the directory saved by acp init.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

SERVICE_USER="<user>"
ENABLE=0
PUBLIC_ORIGIN=""
CONFIGURE_ORIGIN=0
ORIGIN_ONLY=0
RUN_ROOT=""
CONFIGURE_RUN_ROOT=0
RUN_ROOT_ONLY=0
while [[ $# -gt 0 ]]; do
  case "$1" in
    --user) SERVICE_USER="$2"; shift 2 ;;
    --enable) ENABLE=1; shift ;;
    --public-origin) PUBLIC_ORIGIN="$2"; CONFIGURE_ORIGIN=1; shift 2 ;;
    --origin-only) ORIGIN_ONLY=1; shift ;;
    --run-root) RUN_ROOT="$2"; CONFIGURE_RUN_ROOT=1; shift 2 ;;
    --run-root-only) RUN_ROOT_ONLY=1; shift ;;
    *) echo "Unknown arg: $1" >&2; exit 1 ;;
  esac
done

if [[ "$RUN_ROOT_ONLY" -eq 1 && "$CONFIGURE_RUN_ROOT" -eq 0 ]]; then
  echo "--run-root-only requires --run-root (use an empty value to read acp init config)." >&2
  exit 1
fi
if [[ -n "$RUN_ROOT" ]]; then
  python3 - "$RUN_ROOT" <<'PY'
import sys
from pathlib import Path

value = sys.argv[1]
if not Path(value).is_absolute() or any(c in value for c in ('"', '\\', '%', '\n', '\r')):
    raise ValueError('Run root must be an absolute path safe for systemd Environment')
PY
fi

if [[ "$ORIGIN_ONLY" -eq 1 && "$CONFIGURE_ORIGIN" -eq 0 ]]; then
  echo "--origin-only requires --public-origin (use an empty value for direct access)." >&2
  exit 1
fi

# Validate before touching the service. This pure Services contract needs only
# the stdlib and works even before the project's virtualenv is installed.
if [[ "$CONFIGURE_ORIGIN" -eq 1 ]]; then
  PYTHONPATH="$PROJECT_ROOT/src" python3 - "$PUBLIC_ORIGIN" <<'PY'
import sys
from acp_services.workspace.boundary import OriginPolicy

origin = sys.argv[1]
OriginPolicy(public_origin=origin or None)
if any(char in origin for char in ('"', '\\', '%')):
    raise ValueError('Public origin contains characters unsafe for a systemd Environment value')
PY
fi

UNIT_FILE="/etc/systemd/system/acp.service"
if [[ "$ORIGIN_ONLY" -eq 0 && "$RUN_ROOT_ONLY" -eq 0 ]]; then
GROUP="$(id -gn "$SERVICE_USER")"

echo ">> Project root : $PROJECT_ROOT"
echo ">> Service user : $SERVICE_USER ($GROUP)"
echo ">> Unit file    : $UNIT_FILE"

sudo tee "$UNIT_FILE" >/dev/null <<EOF
[Unit]
Description=ACP — Auto-Calc Platform Web Dashboard
After=network.target

[Service]
Type=simple
User=$SERVICE_USER
Group=$GROUP
WorkingDirectory=$PROJECT_ROOT
Environment=ACP_RUN_ROOT=
StateDirectory=acp
LogsDirectory=acp
ExecStart=$PROJECT_ROOT/scripts/start_acp.sh
Restart=on-failure
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF
fi

if [[ "$CONFIGURE_ORIGIN" -eq 1 ]]; then
  # Keep deployment-specific domains outside the generated main unit and repo.
  sudo mkdir -p /etc/systemd/system/acp.service.d
  sudo tee /etc/systemd/system/acp.service.d/public-origin.conf >/dev/null <<EOF
# Generated by scripts/install_systemd.sh --public-origin
[Service]
Environment="ACP_PUBLIC_ORIGIN=$PUBLIC_ORIGIN"
EOF
fi

if [[ "$CONFIGURE_RUN_ROOT" -eq 1 ]]; then
  sudo mkdir -p /etc/systemd/system/acp.service.d
  sudo tee /etc/systemd/system/acp.service.d/run-root.conf >/dev/null <<EOF
# Generated by scripts/install_systemd.sh --run-root
[Service]
Environment="ACP_RUN_ROOT=$RUN_ROOT"
EOF
fi

sudo systemctl daemon-reload
echo ">> Reloaded systemd."

if [[ "$ENABLE" -eq 1 ]]; then
  sudo systemctl enable --now acp
  echo ">> Enabled + started acp.service"
else
  sudo systemctl restart acp
  echo ">> Restarted acp.service"
fi

systemctl is-active acp
