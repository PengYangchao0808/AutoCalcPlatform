/**
 * Self-contained offline install surface for the RPH tarball set.
 *
 * The workspace keeps its packages `private: true`, so the packed tarballs
 * keep internal dependencies as plain semver versions (`@rph/bridge@0.0.0`).
 * Installing those tarballs as-is makes pnpm ask the public registry for
 * `@rph/*` — the 2026-10-26 clean-host probe failed exactly there with
 * `ERR_PNPM_FETCH_404`.
 *
 * This module removes the registry from the graph:
 *
 *   - `rph-install.package.json` declares every package as `file:./*.tgz`;
 *   - `pnpm-workspace.yaml` carries `overrides` that pin *transitive* `@rph/*`
 *     dependencies to the same tarballs (pnpm 11 no longer reads the `pnpm`
 *     field of package.json, so the settings live in the workspace file);
 *   - `pnpm-lock.yaml` is generated from that surface and must contain no
 *     registry resolution for `@rph/*`;
 *   - `SHA256SUMS` covers every shipped byte.
 *
 * The functions here are pure enough for `rph/test/install-surface.test.mjs`
 * to exercise the guards without packaging anything.
 */

import { createHash } from "node:crypto";
import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";

/** Private npm scope owned by this workspace. */
export const RPH_SCOPE = "@rph/";

/** Canonical package order (also the dependency order). */
export const PACKAGE_NAMES = Object.freeze([
  "research",
  "bridge",
  "dsh-bundle",
  "cli",
]);

export const INSTALL_MANIFEST_NAME = "rph-install.package.json";
export const INSTALL_PACKAGE_NAME = "package.json";
export const INSTALL_WORKSPACE_NAME = "pnpm-workspace.yaml";
export const INSTALL_LOCKFILE_NAME = "pnpm-lock.yaml";
export const PACKAGE_INDEX_NAME = "rph-packages.json";
export const CHECKSUM_NAME = "SHA256SUMS";
export const README_NAME = "README.md";
export const VERIFY_SCRIPT_NAME = "verify-install.mjs";

export const PACKAGE_INDEX_SCHEMA = "acp2.rph.packages.v1";
export const PACKAGE_MANAGER = "pnpm@11.28.5";
export const NODE_ENGINE = "^22.19.0 || >=24.0.0";

/** Public registries that must never appear in the generated lockfile. */
const REGISTRY_MARKERS = Object.freeze([
  "registry.npmjs.org",
  "registry.yarnpkg.com",
  "registry.npmmirror.com",
]);

const RPH_LOCK_ENTRY = /^ {2}'(@rph\/[^']+)':$/gm;

export function internalPackageName(name) {
  return `${RPH_SCOPE}${name}`;
}

export function tarballName(name, version) {
  return `rph-${name}-${version}.tgz`;
}

export function localFileSpecifier(file) {
  return `file:./${file}`;
}

function ordered(packages) {
  const byName = new Map(packages.map((entry) => [entry.name, entry]));
  const missing = PACKAGE_NAMES.filter((name) => !byName.has(name));
  if (missing.length > 0) {
    throw new Error(`install surface is missing package(s): ${missing.join(", ")}`);
  }
  const extra = packages
    .map((entry) => entry.name)
    .filter((name) => !PACKAGE_NAMES.includes(name));
  if (extra.length > 0) {
    throw new Error(`install surface has unknown package(s): ${extra.join(", ")}`);
  }
  return PACKAGE_NAMES.map((name) => byName.get(name));
}

/** Consumer manifest: every private package is a local tarball. */
export function buildInstallManifest(packages) {
  const dependencies = {};
  for (const entry of ordered(packages)) {
    dependencies[internalPackageName(entry.name)] = localFileSpecifier(entry.file);
  }
  return {
    name: "rph-install",
    version: "0.0.0",
    private: true,
    description:
      "Self-contained offline install surface for the RPH release tarballs (not published to any registry)",
    packageManager: PACKAGE_MANAGER,
    engines: { node: NODE_ENGINE },
    type: "module",
    dependencies,
  };
}

/**
 * pnpm 11 reads install settings from `pnpm-workspace.yaml`; a `pnpm` field in
 * package.json is ignored with a warning. The overrides are what keep
 * transitive `@rph/*` dependencies off the registry.
 */
export function renderInstallWorkspace(packages) {
  const lines = [
    "# Generated by rph/scripts/package.mjs — do not edit by hand.",
    "#",
    "# pnpm 11 no longer reads the `pnpm` field of package.json; this file is the",
    "# single authority for install settings. The overrides below rewrite every",
    "# private @rph/* dependency (declared as plain versions inside the packed",
    "# tarballs) to the local tarball. Removing them makes pnpm query",
    "# registry.npmjs.org and fail with ERR_PNPM_FETCH_404.",
    "overrides:",
  ];
  for (const entry of ordered(packages)) {
    lines.push(
      `  "${internalPackageName(entry.name)}": "${localFileSpecifier(entry.file)}"`,
    );
  }
  return `${lines.join("\n")}\n`;
}

/** Artifact index: name/version/size/sha256 for each tarball. */
export function buildPackageIndex(packages) {
  return {
    schema: PACKAGE_INDEX_SCHEMA,
    generated_by: "rph/scripts/package.mjs",
    install_manifest: INSTALL_MANIFEST_NAME,
    install_lockfile: INSTALL_LOCKFILE_NAME,
    install_workspace: INSTALL_WORKSPACE_NAME,
    checksums: CHECKSUM_NAME,
    packages: ordered(packages).map((entry) => ({
      name: entry.name,
      package: internalPackageName(entry.name),
      version: entry.version,
      file: entry.file,
      size: entry.size,
      sha256: entry.sha256,
      license: entry.license ?? null,
      bin: entry.bin ?? null,
    })),
  };
}

export function renderReadme(packages) {
  const rows = ordered(packages)
    .map(
      (entry) =>
        `| \`${internalPackageName(entry.name)}\` | \`${entry.file}\` | \`${entry.sha256}\` |`,
    )
    .join("\n");
  return `# RPH offline install surface

Generated by \`rph/scripts/package.mjs\`. This directory is self-contained: it
holds the four private RPH tarballs plus the manifest, lockfile and checksums
needed to install them **without a checkout and without the public npm
registry**.

The packages are \`private: true\` and are **not published** to any registry;
the tarballs are the release artifacts.

## Prerequisites

- Node \`${NODE_ENGINE}\` (verified with 22.19.0)
- \`${PACKAGE_MANAGER}\` (the pinned \`packageManager\`)

## Install (offline)

Copy this whole directory to the target host, then:

\`\`\`bash
pnpm install --offline --frozen-lockfile
node verify-install.mjs
\`\`\`

\`pnpm install --offline\` never opens a socket: every \`@rph/*\` dependency in
\`rph-install.package.json\` and every transitive \`@rph/*\` override in
\`pnpm-workspace.yaml\` points at a local tarball. Do not run the install inside
the source workspace — copy the directory elsewhere first.

## Files

| File | Purpose |
| --- | --- |
| \`${INSTALL_MANIFEST_NAME}\` | Consumer manifest; identical bytes to \`${INSTALL_PACKAGE_NAME}\` |
| \`${INSTALL_PACKAGE_NAME}\` | Same manifest under the name pnpm reads |
| \`${INSTALL_WORKSPACE_NAME}\` | pnpm 11 settings + \`overrides\` for transitive \`@rph/*\` |
| \`${INSTALL_LOCKFILE_NAME}\` | Lockfile with \`file:\`-only resolutions (no registry entries) |
| \`${PACKAGE_INDEX_NAME}\` | Tarball name/version/size/sha256 index |
| \`${CHECKSUM_NAME}\` | \`sha256sum -c\` compatible digest list |
| \`${VERIFY_SCRIPT_NAME}\` | Checksums + import-resolution verification |

## Artifacts

| Package | Tarball | SHA-256 |
| --- | --- | --- |
${rows}
`;
}

/** Standalone verification script shipped inside the install surface. */
export const VERIFY_SCRIPT = `#!/usr/bin/env node
/**
 * Verify an offline RPH install: checksum the shipped files, then prove every
 * @rph/* import resolves inside this directory (never from a checkout or the
 * registry). Exit code 0 = PASS.
 */

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { closeSync, existsSync, mkdtempSync, openSync, readFileSync, realpathSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const EXPECTED = [
  ["@rph/research", "recordKey"],
  ["@rph/bridge", "BRIDGE_OPERATIONS"],
  ["@rph/dsh-bundle", "BUNDLE_PROFILE_NAMES"],
  ["@rph/cli", "parseArgs"],
];

function sha256(file) {
  return createHash("sha256").update(readFileSync(file)).digest("hex");
}

const sums = readFileSync(join(HERE, "SHA256SUMS"), "utf8")
  .trim()
  .split("\\n")
  .filter(Boolean);
assert.notEqual(sums.length, 0, "SHA256SUMS is empty");
for (const line of sums) {
  const match = /^([0-9a-f]{64}) {2}(.+)$/.exec(line);
  assert.ok(match, "malformed checksum line: " + line);
  const actual = sha256(join(HERE, match[2]));
  assert.equal(actual, match[1], "sha256 mismatch for " + match[2]);
}

const manifest = JSON.parse(
  readFileSync(join(HERE, "rph-install.package.json"), "utf8"),
);
const root = realpathSync(HERE);
const resolved = [];
for (const [name, symbol] of EXPECTED) {
  const spec = manifest.dependencies[name];
  assert.ok(
    typeof spec === "string" && spec.startsWith("file:"),
    name + " is not a local tarball dependency: " + String(spec),
  );
  const path = realpathSync(fileURLToPath(import.meta.resolve(name)));
  assert.ok(
    path.startsWith(root + "/node_modules/"),
    name + " resolved outside the install surface: " + path,
  );
  const module = await import(name);
  assert.ok(module[symbol] !== undefined, name + " is missing export " + symbol);
  resolved.push(name + " -> " + path);
}

// The published bin, executed from an unrelated absolute directory with no
// checkout on the module path, and reporting its own package.json version.
const cliManifest = JSON.parse(
  readFileSync(join(HERE, "node_modules", "@rph", "cli", "package.json"), "utf8"),
);
const binPath = join(HERE, "node_modules", ".bin", "rph");
assert.ok(existsSync(binPath), "the rph bin is not linked into node_modules/.bin");
const elsewhere = mkdtempSync(join(tmpdir(), "rph-bin-"));
const binEnv = { ...process.env };
delete binEnv.ACP2_CONTROLLER_URL;
delete binEnv.PYTHONPATH;

// Regular-file capture also works where synchronous subprocess pipe creation
// is restricted. Always inspect spawn errors: status alone can be misleading.
let invocation = 0;
function runBin(args) {
  const outputPath = join(elsewhere, "stdout-" + invocation);
  const errorPath = join(elsewhere, "stderr-" + invocation++);
  const out = openSync(outputPath, "w");
  const err = openSync(errorPath, "w");
  let result;
  try {
    result = spawnSync(binPath, args, { cwd: elsewhere, env: binEnv,
      stdio: ["ignore", out, err], timeout: 60000 });
  } finally {
    closeSync(out);
    closeSync(err);
  }
  assert.equal(result.error, undefined, "rph bin launch failed: " + String(result.error));
  return { ...result, stdout: readFileSync(outputPath, "utf8"), stderr: readFileSync(errorPath, "utf8") };
}

const version = runBin(["--version"]);
assert.equal(version.status, 0, "rph --version failed: " + String(version.stderr));
assert.equal(
  version.stdout.trim(),
  "rph " + cliManifest.version,
  "the bin prints a version that is not its package.json version",
);

const help = runBin(["--help"]);
assert.equal(help.status, 0, "rph --help failed: " + String(help.stderr));
for (const command of ["rph research", "rph resume", "rph doctor"]) {
  assert.ok(help.stdout.includes(command), "rph --help does not list " + command);
}

const doctor = runBin(["doctor", "--json"]);
assert.ok(
  doctor.status === 0 || doctor.status === 1,
  "rph doctor --json exited with " + String(doctor.status),
);
const report = JSON.parse(doctor.stdout);
assert.equal(report.schema, "acp2.rph.doctor.v1");
assert.ok(Array.isArray(report.checks) && report.checks.length > 0, "doctor reported no checks");

console.log("RPH INSTALL VERIFY PASS");
for (const line of resolved) console.log("  " + line);
console.log("  bin: rph " + cliManifest.version + " (from an unrelated cwd)");
console.log("  doctor: schema " + report.schema + ", " + report.checks.length + " checks");
`;

export function renderVerifyScript() {
  return VERIFY_SCRIPT;
}

export function sha256File(file) {
  return createHash("sha256").update(readFileSync(file)).digest("hex");
}

/** Fail when an internal dependency is not a local tarball. */
export function assertNoRegistrySpecifiers(manifest) {
  const dependencies = manifest?.dependencies;
  if (dependencies === undefined || dependencies === null) {
    throw new Error("install manifest has no dependencies block");
  }
  const names = Object.keys(dependencies).sort();
  const expected = [...PACKAGE_NAMES].map(internalPackageName).sort();
  if (JSON.stringify(names) !== JSON.stringify(expected)) {
    throw new Error(
      `install manifest dependencies ${JSON.stringify(names)} != ${JSON.stringify(expected)}`,
    );
  }
  for (const [name, specifier] of Object.entries(dependencies)) {
    if (typeof specifier !== "string" || !specifier.startsWith("file:")) {
      throw new Error(
        `${name} would be resolved from a registry: expected file:./*.tgz, got ${JSON.stringify(specifier)}`,
      );
    }
  }
  return manifest;
}

/** Fail when pnpm-workspace.yaml does not pin every package to a tarball. */
export function assertOverridesCoverage(workspaceText, packages) {
  const found = new Map();
  for (const line of workspaceText.split("\n")) {
    const match = /^ {2}"(@rph\/[^"]+)": "(file:[^"]+)"$/.exec(line);
    if (match !== null) found.set(match[1], match[2]);
  }
  for (const entry of ordered(packages)) {
    const name = internalPackageName(entry.name);
    const specifier = found.get(name);
    if (specifier === undefined) {
      throw new Error(`pnpm-workspace.yaml is missing an override for ${name}`);
    }
    if (!specifier.startsWith("file:")) {
      throw new Error(`${name} override is not a local tarball: ${specifier}`);
    }
  }
  if (found.size !== PACKAGE_NAMES.length) {
    throw new Error(
      `pnpm-workspace.yaml has ${found.size} @rph/* overrides, expected ${PACKAGE_NAMES.length}`,
    );
  }
  return workspaceText;
}

/**
 * Fail when the lockfile can reach the registry for a private package.
 *
 * Every `@rph/*` lock entry (packages and snapshots sections) must be keyed by
 * an explicit `file:` tarball, and no public registry URL may appear at all.
 */
export function assertNoRegistryResolution(lockfileText) {
  for (const marker of REGISTRY_MARKERS) {
    if (lockfileText.includes(marker)) {
      throw new Error(`lockfile references the public registry: ${marker}`);
    }
  }
  const keys = [...lockfileText.matchAll(RPH_LOCK_ENTRY)].map((match) => match[1]);
  if (keys.length === 0) {
    throw new Error("lockfile has no @rph/* entries");
  }
  for (const key of keys) {
    if (!key.includes("@file:")) {
      throw new Error(`lockfile entry ${key} is not pinned to a local tarball`);
    }
  }
  for (const name of PACKAGE_NAMES) {
    const expected = `${internalPackageName(name)}@file:`;
    if (!keys.some((key) => key.startsWith(expected))) {
      throw new Error(`lockfile is missing a file: entry for @rph/${name}`);
    }
  }
  return lockfileText;
}

export function writeInstallSurface(directory, packages) {
  const manifest = buildInstallManifest(packages);
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
  writeFileSync(join(directory, INSTALL_MANIFEST_NAME), manifestText);
  writeFileSync(join(directory, INSTALL_PACKAGE_NAME), manifestText);
  writeFileSync(
    join(directory, INSTALL_WORKSPACE_NAME),
    renderInstallWorkspace(packages),
  );
  writeFileSync(
    join(directory, PACKAGE_INDEX_NAME),
    `${JSON.stringify(buildPackageIndex(packages), null, 2)}\n`,
  );
  writeFileSync(join(directory, README_NAME), renderReadme(packages));
  writeFileSync(join(directory, VERIFY_SCRIPT_NAME), renderVerifyScript());
  return manifest;
}

export function listSurfaceFiles(directory) {
  return readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name !== CHECKSUM_NAME)
    .map((entry) => entry.name)
    .sort();
}

export function writeChecksums(directory) {
  const lines = listSurfaceFiles(directory).map(
    (name) => `${sha256File(join(directory, name))}  ${name}`,
  );
  writeFileSync(join(directory, CHECKSUM_NAME), `${lines.join("\n")}\n`);
  return lines;
}

export function readChecksums(directory) {
  const text = readFileSync(join(directory, CHECKSUM_NAME), "utf8");
  return text
    .split("\n")
    .filter((line) => line.trim() !== "")
    .map((line) => {
      const match = /^([0-9a-f]{64}) {2}(.+)$/.exec(line);
      if (match === null) throw new Error(`malformed checksum line: ${line}`);
      return { sha256: match[1], file: match[2] };
    });
}

/** Verify checksums and that every shipped file is covered by them. */
export function verifyChecksums(directory) {
  const entries = readChecksums(directory);
  const listed = new Set();
  for (const entry of entries) {
    const path = join(directory, entry.file);
    if (!existsSync(path)) {
      throw new Error(`checksum lists a missing file: ${entry.file}`);
    }
    const actual = sha256File(path);
    if (actual !== entry.sha256) {
      throw new Error(
        `sha256 mismatch for ${entry.file}: expected ${entry.sha256}, got ${actual}`,
      );
    }
    listed.add(entry.file);
  }
  for (const name of listSurfaceFiles(directory)) {
    if (!listed.has(name)) {
      throw new Error(`${name} is not covered by ${CHECKSUM_NAME}`);
    }
  }
  return entries;
}

/**
 * Re-validate a generated install surface from bytes on disk.
 *
 * Returns the parsed artifact index; throws on any digest, manifest, override
 * or lockfile violation.
 */
export function verifyInstallSurface(directory) {
  const indexPath = join(directory, PACKAGE_INDEX_NAME);
  if (!existsSync(indexPath)) {
    throw new Error(`missing ${PACKAGE_INDEX_NAME} in ${directory}`);
  }
  const index = JSON.parse(readFileSync(indexPath, "utf8"));
  if (index.schema !== PACKAGE_INDEX_SCHEMA) {
    throw new Error(`unexpected package index schema: ${String(index.schema)}`);
  }
  if (index.packages.length !== PACKAGE_NAMES.length) {
    throw new Error(
      `package index lists ${index.packages.length} packages, expected ${PACKAGE_NAMES.length}`,
    );
  }
  for (const entry of index.packages) {
    const path = join(directory, entry.file);
    if (!existsSync(path)) throw new Error(`missing tarball: ${entry.file}`);
    const size = statSync(path).size;
    if (size !== entry.size) {
      throw new Error(
        `size mismatch for ${entry.file}: index ${entry.size}, file ${size}`,
      );
    }
    const digest = sha256File(path);
    if (digest !== entry.sha256) {
      throw new Error(
        `sha256 mismatch for ${entry.file}: index ${entry.sha256}, file ${digest}`,
      );
    }
  }

  const manifestPath = join(directory, INSTALL_MANIFEST_NAME);
  const packagePath = join(directory, INSTALL_PACKAGE_NAME);
  const manifestText = readFileSync(manifestPath, "utf8");
  if (manifestText !== readFileSync(packagePath, "utf8")) {
    throw new Error(
      `${INSTALL_PACKAGE_NAME} and ${INSTALL_MANIFEST_NAME} must have identical bytes`,
    );
  }
  const manifest = assertNoRegistrySpecifiers(JSON.parse(manifestText));
  if (manifest.private !== true) {
    throw new Error("install manifest must stay private");
  }
  if (Object.hasOwn(manifest, "pnpm")) {
    throw new Error(
      "install manifest must not carry a `pnpm` field (pnpm 11 ignores it); put settings in pnpm-workspace.yaml",
    );
  }

  assertOverridesCoverage(
    readFileSync(join(directory, INSTALL_WORKSPACE_NAME), "utf8"),
    index.packages,
  );
  assertNoRegistryResolution(
    readFileSync(join(directory, INSTALL_LOCKFILE_NAME), "utf8"),
  );
  verifyChecksums(directory);
  return index;
}
