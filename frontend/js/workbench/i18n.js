// ── Translation helpers ──
function t(key, vars) {
  const dict = I18N[currentLang] || I18N["zh-CN"];
  let value = dict[key] || I18N["zh-CN"][key] || key;
  if (vars) {
    Object.keys(vars).forEach(function(name) {
      value = value.split("{" + name + "}").join(String(vars[name]));
    });
  }
  return value;
}

function translateStatus(status) {
  const raw = String(status || "").trim();
  const key = "status." + raw.toLowerCase();
  const translated = t(key);
  return translated === key ? (raw || t("common.unknown")) : translated;
}

function translateStageName(name, backendLabel) {
  const raw = String(name || "").trim();
  if (!raw) return backendLabel || "";
  const key = "stage." + raw;
  const translated = t(key);
  if (translated !== key) return translated;
  if (backendLabel && String(backendLabel).trim()) return String(backendLabel).trim();
  return raw.replace(/_/g, " ");
}

function formatRelativeTime(isoStr) {
  if (!isoStr) return "";
  const ts = new Date(isoStr).getTime();
  if (isNaN(ts)) return "";
  const diff = Math.max(0, Math.floor((Date.now() - ts) / 1000));
  if (diff < 10) return t("time.just_now");
  if (diff < 60) return t("time.seconds_ago", { n: diff });
  const min = Math.floor(diff / 60);
  if (min < 60) return t("time.minutes_ago", { n: min });
  const hrs = Math.floor(min / 60);
  if (hrs < 24) return t("time.hours_ago", { n: hrs });
  const days = Math.floor(hrs / 24);
  return t("time.days_ago", { n: days });
}

// Phase E: unified study status (backend-authoritative, display-only).
function translateStudyStatus(unifiedStatus) {
  const raw = String(unifiedStatus || "").trim();
  if (!raw) return "";
  const key = "study.status." + raw;
  const translated = t(key);
  return translated === key ? raw : translated;
}

function getStudyStatusClass(unifiedStatus) {
  const s = String(unifiedStatus || "").toUpperCase();
  if (s === "COMPLETED") return "completed";
  if (s === "FAILED") return "failed";
  if (s === "SR_WAITING_REVIEW") return "waiting_review";
  if (/_RUNNING$/.test(s)) return "running";
  // DRAFT / RESUMABLE (+ unknown) → queued.
  return "queued";
}

function truncateConfigHash(hash) {
  const raw = String(hash || "").trim();
  if (!raw) return "";
  return raw.length > 12 ? raw.slice(0, 12) + "…" : raw;
}

// Phase E: unified_status from cached detail (flat or {study:{...}}), then the
// study-list cache — never refetches.
function getMechanismUnifiedStatus(studyId) {
  const detail = mechanismStudyDetailsById[String(studyId || "")];
  if (isPlainObject(detail)) {
    if (typeof detail.unified_status === "string" && detail.unified_status) return detail.unified_status;
    if (isPlainObject(detail.study) && typeof detail.study.unified_status === "string" && detail.study.unified_status) {
      return detail.study.unified_status;
    }
  }
  const studies = mechanismStudiesByJob[String(mechanismViewerState.jobId || "")] || [];
  const match = studies.filter(function(entry) { return entry && String(entry.id) === String(studyId); })[0];
  return match && typeof match.unified_status === "string" ? match.unified_status : "";
}

